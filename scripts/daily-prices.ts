/**
 * Writes each mapped Product's recent price per day, in its Ingredient's unit,
 * to the file the basket page draws its price history from (#16). See
 * src/catalogue/daily.ts.
 *
 *   node scripts/daily-prices.ts --catalogue prototype/catalogue.js \
 *     --history history.json --out prototype/prices.js
 *
 * A plain script assigning window.PRICES, like catalogue.js, so the page can
 * load it opened from disk. Without it the page simply shows no history.
 */

import { readFile, writeFile } from "node:fs/promises";
import { parseCatalogueScript } from "../src/catalogue/assess.ts";
import { dailyPrices, type UnitBasis } from "../src/catalogue/daily.ts";
import type { PriceHistory } from "../src/catalogue/history.ts";

const argv = process.argv.slice(2);
const arg = (name: string) => { const i = argv.indexOf(name); return i >= 0 ? argv[i + 1] ?? "" : ""; };
const [cataloguePath, historyPath, out] = [arg("--catalogue"), arg("--history"), arg("--out")];
if (!cataloguePath || !historyPath || !out) {
  console.error("Usage: node scripts/daily-prices.ts --catalogue <file> --history <file> --out <file>");
  process.exit(2);
}

const data = parseCatalogueScript(await readFile(cataloguePath, "utf8")) as unknown as { columns: string[]; catalogue: Record<string, unknown[][]> };
const history = JSON.parse(await readFile(historyPath, "utf8")) as PriceHistory;
const col = (name: string) => data.columns.indexOf(name);
const [REF, SHELF, OFFER, WORDING, PRICE, PACK] = ["ref", "shelfPriceCents", "offerPriceCents", "offerWording", "ingredientUnitPriceCents", "ingredientPack"].map(col) as number[];

const bases: Record<string, UnitBasis[]> = {};
for (const [chainId, rows] of Object.entries(data.catalogue)) {
  bases[chainId] = rows.filter((r) => r[PRICE!] !== null).map((r) => {
    const onOffer = r[OFFER!] !== null || !!r[WORDING!];
    return {
      ref: r[REF!] as string,
      ingredientPack: r[PACK!] as number | null,
      ingredientUnitPriceCents: r[PRICE!] as number,
      paidTodayCents: (onOffer && r[OFFER!] !== null ? r[OFFER!] : r[SHELF!]) as number,
    };
  });
}

const prices = dailyPrices(history, bases);
await writeFile(out, `// Generated by scripts/daily-prices.ts. Do not edit.\nwindow.PRICES = ${JSON.stringify(prices)};\n`);
const counts = Object.entries(prices.series).map(([c, s]) => `${c} ${Object.keys(s).length}`).join(", ");
console.log(`wrote ${out}: ${prices.dates.length} day(s) for ${counts} Products`);
