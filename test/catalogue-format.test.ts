import { test } from "node:test";
import assert from "node:assert/strict";
import { catalogueScript, COLUMNS, HISTORY_COLUMNS, parseCatalogueScript, productsOf, toRow, withColumns, type Catalogue } from "../src/catalogue/format.ts";

/**
 * The catalogue's positional rows, written and read by column name, so a
 * column added or moved shifts no reader's numbers.
 */

const kaas = { ref: "k1", name: "Jonge kaas 500 g", packQuantity: 0.5, packUnit: "kg", comparisonUnit: "kg", shelfPriceCents: 500, ingredient: "kaas", flags: 2 } as const;
const catalogue = (columns: readonly string[]): Catalogue => ({ chains: [{ id: "dirk", name: "Dirk", observedAt: "2026-10-14" }], columns, vocabulary: [], catalogue: { dirk: [toRow(kaas, columns)] } });

test("a Product reads back by name, whatever order the columns are in", () => {
  for (const columns of [COLUMNS, [...COLUMNS].reverse()]) {
    const [p] = productsOf(catalogue(columns), "dirk");
    assert.equal(p!.name, "Jonge kaas 500 g");
    assert.equal(p!.shelfPriceCents, 500);
    assert.equal(p!.flags, 2);
    assert.equal(p!.offerPriceCents, null, "a field the Product lacks is null");
  }
});

test("a column the catalogue lacks reads as null, as history before apply-history", () => {
  const [p] = productsOf(catalogue(COLUMNS), "dirk");
  assert.equal(p!.referenceLowCents, null);
  assert.deepEqual(productsOf(catalogue(COLUMNS), "lidl"), [], "an unknown Chain has no Products");
});

test("history columns are appended to every row, and read back by name", () => {
  const c = withColumns(catalogue(COLUMNS), HISTORY_COLUMNS, (p) => [p.shelfPriceCents - 50, 14]);
  assert.deepEqual(c.columns, [...COLUMNS, ...HISTORY_COLUMNS]);
  const [p] = productsOf(c, "dirk");
  assert.equal(p!.referenceLowCents, 450);
  assert.equal(p!.referenceDays, 14);
  assert.equal(p!.name, "Jonge kaas 500 g");
});

test("the script the page loads parses back to the same catalogue", () => {
  const c = catalogue(COLUMNS);
  const text = catalogueScript(c, "a test");
  assert.match(text, /^\/\/ Generated by a test\. Do not edit\.\nwindow\.CATALOGUE = \{/);
  assert.deepEqual(parseCatalogueScript(text), c);
  assert.throws(() => parseCatalogueScript("{}"), /not a catalogue script/);
});
