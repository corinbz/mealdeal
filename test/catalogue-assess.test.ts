import { test } from "node:test";
import assert from "node:assert/strict";
import { assessCatalogue, parseCatalogueScript, type Catalogue } from "../src/catalogue/assess.ts";

/**
 * The guard between the morning refresh and the catalogue the basket page
 * runs on. Ingest's volume alarm cannot fire in the refresh's throwaway
 * database, so this comparison with the published catalogue is the only thing
 * standing between a Chain's changed API and an emptied Basket comparison.
 */

const EXPECT = { date: "2026-10-14", chains: ["dirk", "jumbo"], minRatio: 0.5 };

function catalogue(counts: Record<string, number>, observedAt = "2026-10-14"): Catalogue {
  return {
    chains: Object.keys(counts).map((id) => ({ id, observedAt })),
    catalogue: Object.fromEntries(Object.entries(counts).map(([id, n]) => [id, Array.from({ length: n }, () => [])])),
  };
}

test("a full day may replace the published catalogue", () => {
  const published = catalogue({ dirk: 7359, jumbo: 17104 }, "2026-10-13");
  assert.deepEqual(assessCatalogue(catalogue({ dirk: 7300, jumbo: 17200 }), published, EXPECT), []);
});

test("the first publish needs no published catalogue", () => {
  assert.deepEqual(assessCatalogue(catalogue({ dirk: 7359, jumbo: 17104 }), null, EXPECT), []);
});

test("a Chain that shrank below half of the published count is refused", () => {
  const published = catalogue({ dirk: 7359, jumbo: 17104 }, "2026-10-13");
  const problems = assessCatalogue(catalogue({ dirk: 7359, jumbo: 76 }), published, EXPECT);
  assert.equal(problems.length, 1);
  assert.match(problems[0]!, /jumbo has 76 comparable Products, under 50% of the 17104 published/);
});

test("a Chain whose only prices are its Offers may shrink, but never to nothing", () => {
  // Lidl lists a new set of Offers each week, some weeks far fewer.
  const offersOnly = (counts: Record<string, number>, observedAt?: string): Catalogue => {
    const c = catalogue(counts, observedAt);
    return { ...c, chains: c.chains.map((x) => (x.id === "lidl" ? { ...x, offersOnly: true } : x)) };
  };
  const expect = { ...EXPECT, chains: ["dirk", "lidl"] };
  const published = offersOnly({ dirk: 7359, lidl: 88 }, "2026-10-13");
  assert.deepEqual(assessCatalogue(offersOnly({ dirk: 7359, lidl: 30 }), published, expect), []);
  assert.deepEqual(assessCatalogue(offersOnly({ dirk: 7359, lidl: 0 }), published, expect), ["lidl has no comparable Products"]);
});

test("a missing or empty Chain is refused, even on the first publish", () => {
  const problems = assessCatalogue(catalogue({ dirk: 7359, jumbo: 0 }), null, { ...EXPECT, chains: ["dirk", "jumbo", "spar"] });
  assert.deepEqual(problems, ["jumbo has no comparable Products", "spar is missing from the catalogue"]);
});

test("prices from any day but the one swept are refused", () => {
  const problems = assessCatalogue(catalogue({ dirk: 7359, jumbo: 17104 }, "2026-10-13"), null, EXPECT);
  assert.equal(problems.length, 2);
  assert.match(problems[0]!, /dirk prices are from 2026-10-13, not 2026-10-14/);
});

test("an older day never replaces a newer published one", () => {
  const published = catalogue({ dirk: 7359, jumbo: 17104 }, "2026-10-15");
  const problems = assessCatalogue(catalogue({ dirk: 7359, jumbo: 17104 }), published, EXPECT);
  assert.equal(problems.length, 2);
  assert.match(problems[0]!, /published dirk prices are from 2026-10-15, newer than 2026-10-14/);
});

test("reads the script the basket page loads", () => {
  const text = `// Generated by scripts/catalogue-from-db.ts. Do not edit.\nwindow.CATALOGUE = ${JSON.stringify(catalogue({ dirk: 2 }))};\n`;
  assert.equal(parseCatalogueScript(text).catalogue["dirk"]!.length, 2);
  assert.throws(() => parseCatalogueScript("{}"), /not a catalogue script/);
});
